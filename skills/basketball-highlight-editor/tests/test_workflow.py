"""Behavioral tests: state gates, source integrity, review and independent versions."""
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch
from types import SimpleNamespace as Args

spec=importlib.util.spec_from_file_location('highlight',Path(__file__).parents[1]/'scripts/highlight.py')
h=importlib.util.module_from_spec(spec);spec.loader.exec_module(h)


class Workflow(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp=tempfile.TemporaryDirectory()
        cls.base=Path(cls.tmp.name)
        cls.video=cls.base/'silent source.mp4'
        h.run(['ffmpeg','-v','error','-f','lavfi','-i','color=c=blue:s=320x240:d=2',
               '-c:v','libx264','-y',cls.video])
        cls.rights=cls.base/'rights.json'
        h.write(cls.rights,dict(source_url='synthetic:ffmpeg-color',license='test fixture',
                creator='test suite',processing_basis='generated by test',restrictions='test only'))

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def setUp(self):
        self.root=self.base/self._testMethodName
        h.cmd_init(Args(project=self.root,video=self.video,rights=self.rights))
        self.manifest=self.base/'manifest.json'
        h.write(self.manifest,{'provenance':'synthetic test time ranges','candidates':[
            {'start':0,'end':1},{'start':1,'end':2}]})
        h.cmd_import(Args(project=self.root,file=self.manifest))
        self.annotation=self.base/'annotations.json'
        self.data={'reviewer':{'kind':'test_operator','name':'unittest'},
           'players':[{'id':'white21','description':'white 21','reference':'synthetic fixture'}],
           'assignments':[{'candidate_id':'c0001','player_id':'white21','certainty':'high',
              'reason':'synthetic verified number','evidence':[{'kind':'number_visible','time':.5,'detail':'21'}]},
              {'candidate_id':'c0002','player_id':None,'certainty':'uncertain',
               'reason':'occluded','evidence':[]}]}

    def select(self):
        h.write(self.annotation,self.data)
        h.cmd_annotate(Args(project=self.root,file=self.annotation))
        h.cmd_select(Args(project=self.root,player='white21',selected_by='unittest fixture'))

    def decision(self,**kw):
        _,p=h.load(self.root)
        data={'project_revision':p['revision'],'player_id':'white21',
              'reviewer_kind':'test_operator','reviewer':'unittest',
              'decisions':{'c0001':'keep','c0002':'reject'},**kw}
        f=self.base/'decision.json';h.write(f,data)
        return f

    def test_color_alone_cannot_be_high(self):
        self.data['assignments'][0]['evidence']=[{'kind':'color','time':.5,'detail':'white'}]
        h.write(self.annotation,self.data)
        with self.assertRaisesRegex(ValueError,'HIGH_REQUIRES'):
            h.cmd_annotate(Args(project=self.root,file=self.annotation))

    def test_uncertainty_stays_separate(self):
        self.select();_,p=h.load(self.root)
        self.assertEqual(p['selection']['high_confidence'],['c0001'])
        self.assertEqual(p['selection']['uncertain'],['c0002'])

    def prepare_person_scan(self):
        _,p=h.load(self.root)
        p['samples']=[{'id':'s001','player_id':'white21','description':'plain white shirt',
            'time':0,'bbox_xyxy':[0,0,40,100],'reviewer_kind':'test_operator','reference':'synthetic sample'}]
        data={'video_sha256':p['source']['sha256'],'descriptor_version':'clothing-v2','records':[]}
        h.write(self.root/'people/detections.json',data)
        p['person_detector']={'data':'people/detections.json','data_sha256':h.sha(self.root/'people/detections.json')}
        h.write(self.root/'project.json',p)

    def test_person_scan_tampering_is_rejected(self):
        self.prepare_person_scan()
        h.write(self.root/'people/detections.json',{'changed':True})
        with patch.dict('sys.modules',{'person_match':Args(predict=lambda *a:None)}):
            with self.assertRaisesRegex(ValueError,'PERSON_SCAN_MISSING_OR_CHANGED'):
                h.cmd_match_people(Args(project=self.root,player='white21',apply=True))

    def test_model_matching_invalidates_confirmation_and_preserves_review_kind(self):
        self.select();h.cmd_confirm(Args(project=self.root,file=self.decision()))
        self.prepare_person_scan()
        prediction={'records':[{'time':t,'accepted':[{'player_id':'white21','observation_id':str(t),
            'box':[0,0,40,100],'track_id':0,'distance':.1}]} for t in (0,.333,.667)]}
        with patch.dict('sys.modules',{'person_match':Args(predict=lambda *a:prediction)}):
            h.cmd_match_people(Args(project=self.root,player='white21',apply=True))
        _,p=h.load(self.root)
        self.assertIsNone(p['confirmation']);self.assertIsNone(p['selection'])
        self.assertEqual(p['samples'][0]['reviewer_kind'],'test_operator')
        self.assertEqual(p['candidates'][0]['assignment']['reviewer']['kind'],'local_model')
        self.assertEqual(p['candidates'][1]['assignment']['certainty'],'uncertain')

    def test_unnumbered_requires_saved_sample(self):
        self.data['assignments'][0]['evidence']=[{'kind':'confirmed_sample_match',
             'time':.5,'detail':'white sleeves, bare knees, white shoes','sample_id':'s001'}]
        h.write(self.annotation,self.data)
        with self.assertRaisesRegex(ValueError,'SAVED_CALIBRATION'):
            h.cmd_annotate(Args(project=self.root,file=self.annotation))
        p=h.read(self.root/'project.json')
        p['samples']=[{'id':'s001','player_id':'white21','reviewer_kind':'test_operator'}]
        h.write(self.root/'project.json',p)
        self.select()
        _,p=h.load(self.root)
        self.assertEqual(p['selection']['high_confidence'],['c0001'])

    def test_duplicate_review_priority_stays_uncertain(self):
        self.data['assignments'][0]['needs_review']=True
        self.select();_,p=h.load(self.root)
        self.assertEqual(p['selection']['high_confidence'],[])
        self.assertEqual(p['selection']['uncertain'],['c0001','c0002'])

    def test_no_version_before_confirmation(self):
        self.select()
        with self.assertRaisesRegex(ValueError,'CONFIRM_SELECTION_FIRST'):
            h.cmd_version(Args(project=self.root,name='x',spec='unused',render=True))

    def test_review_must_include_uncertain(self):
        self.select();f=self.decision(decisions={'c0001':'keep'})
        with self.assertRaisesRegex(ValueError,'REVIEW_EVERY'):
            h.cmd_confirm(Args(project=self.root,file=f))

    def test_stale_review_rejected(self):
        self.select();f=self.decision(project_revision=-1)
        with self.assertRaisesRegex(ValueError,'STALE_REVIEW'):
            h.cmd_confirm(Args(project=self.root,file=f))

    def test_wrong_player_review_rejected(self):
        self.select();f=self.decision(player_id='purple13')
        with self.assertRaisesRegex(ValueError,'WRONG_PLAYER'):
            h.cmd_confirm(Args(project=self.root,file=f))

    def test_user_confirmation_needs_authorization(self):
        self.select();f=self.decision(reviewer_kind='user')
        with self.assertRaisesRegex(ValueError,'AUTHORIZATION_REFERENCE'):
            h.cmd_confirm(Args(project=self.root,file=f))

    def test_confirm_saves_edl_without_render(self):
        self.select();h.cmd_confirm(Args(project=self.root,file=self.decision()))
        _,p=h.load(self.root)
        self.assertEqual(p['state'],'awaiting_edit_prompt')
        self.assertTrue((self.root/'confirmed-edl.json').is_file())
        self.assertEqual(list(self.root.rglob('reel.mp4')),[])
        self.assertEqual(p['confirmation']['reviewer_kind'],'test_operator')

    def test_excluded_clip_cannot_reenter_version(self):
        self.select();h.cmd_confirm(Args(project=self.root,file=self.decision()))
        f=self.base/'spec.json';h.write(f,{'prompt':'include rejected clip','clip_ids':['c0002']})
        with self.assertRaisesRegex(ValueError,'CONFIRMED_CLIPS'):
            h.cmd_version(Args(project=self.root,name='bad',spec=f,render=False))

    def test_two_versions_keep_master_and_render_silent_source(self):
        self.select();h.cmd_confirm(Args(project=self.root,file=self.decision()))
        master=(self.root/'confirmed-edl.json').read_bytes()
        f=self.base/'spec.json'
        for name,duration in [('short',.5),('long',1)]:
            h.write(f,{'prompt':'test-only '+name,'max_duration':duration})
            h.cmd_version(Args(project=self.root,name=name,spec=f,render=True))
            meta=h.probe(self.root/'versions'/name/'reel.mp4')
            self.assertLess(abs(meta['duration']-duration),.1)
        _,p=h.load(self.root)
        self.assertEqual(master,(self.root/'confirmed-edl.json').read_bytes())
        self.assertEqual(p['state'],'awaiting_edit_prompt')
        self.assertEqual(len(p['versions']),2)

    def test_changed_source_detected(self):
        copy=self.base/'modified.mp4';copy.write_bytes(self.video.read_bytes())
        p=h.read(self.root/'project.json');p['source']['path']=str(copy);h.write(self.root/'project.json',p)
        with copy.open('ab') as f:f.write(b'change')
        with self.assertRaisesRegex(ValueError,'SOURCE_CHANGED'):h.load(self.root)

    def test_portable_relative_source_can_render(self):
        copy=self.root/'source.mp4';copy.write_bytes(self.video.read_bytes())
        p=h.read(self.root/'project.json');p['source']['path']='source.mp4';h.write(self.root/'project.json',p)
        self.select();h.cmd_confirm(Args(project=self.root,file=self.decision()))
        f=self.base/'spec.json';h.write(f,{'prompt':'portable relative source','max_duration':.5})
        h.cmd_version(Args(project=self.root,name='portable',spec=f,render=True))
        self.assertTrue((self.root/'versions/portable/reel.mp4').is_file())
        self.assertEqual(h.read(self.root/'project.json')['source']['path'],'source.mp4')

    def test_out_of_range_candidates_rejected(self):
        for start,end in [(-1,1),(0,3),(float('nan'),1),(1,1),(2.005,2.01)]:
            with self.assertRaises(ValueError):h.stamp_candidates([{'start':start,'end':end}],2)


if __name__=='__main__':
    unittest.main(verbosity=2)
